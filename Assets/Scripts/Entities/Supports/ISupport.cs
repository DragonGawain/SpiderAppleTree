using System;

public interface ISupport : ILevelElement
{
    /// <summary>
    /// Get the amount of support this support grants.
    /// </summary>
    /// <returns>The support value</returns>
    public int GetSupportValue();

    /// <summary>
    /// Get the coordinate that this support is located at.
    /// </summary>
    /// <returns>The support coordinate</returns>
    public Coord GetCoord();

    /// <summary>
    /// Called when a branch is snapped.
    /// </summary>
    /// <param name="lcrd"></param>
    /// <param name="rcrd"></param>
    /// <param name="branch">The.. new branch that was created from the snap?????</param>
    public void OnSnap(Coord lcrd, Coord rcrd, Branch branch);

    public SupportType GetSupportType();

    /// <summary>
    /// Au auto support is a support that is automatically generated by the associated branch.
    /// </summary>
    /// <returns></returns>
    public bool IsAutoSupport();
}

[Obsolete("This is basically a manual GetType. It's silly. I should remove it.")]
public enum SupportType
{
    TRUNK_SUPPORT_V,
    TRUNK_SUPPORT_H,
    WEB_REINFORCEMENT,
    HANGING_WEB_STRING,
    BRANCH_SUPPORT
}
